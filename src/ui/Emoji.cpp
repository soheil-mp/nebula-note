QList<QPair<QString, QString>> search(const QString &query, int limit)
{
    QList<QPair<QString, QString>> prefix, inside;
    const QString q = query.toLower();
    for (const auto &e : all()) {
        if (e.first.startsWith(q))
            prefix.append(e);
        else if (e.first.contains(q))
            inside.append(e);
    }
    QList<QPair<QString, QString>> out = prefix + inside;
    // One entry per emoji (aliases share one).
    QList<QPair<QString, QString>> unique;
    for (const auto &e : out) {
        bool seen = false;
        for (const auto &u : unique)
            seen = seen || u.second == e.second;
        if (!seen)
            unique.append(e);
        if (unique.size() >= limit)
            break;
    }
    return unique;
}
